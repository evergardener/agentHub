def _native_delivery_is_pending(delegation_id: str) -> bool:
    """Return whether Hermes still owns an undelivered native completion."""
    try:
        from tools.async_delegation import get_durable_delegation

        record = get_durable_delegation(delegation_id)
    except Exception:
        # Losing access to the durable ledger must not create duplicate turns.
        # The existing record remains visible through supervision/status and a
        # bridge restart can still restore the native completion.
        return True
    if not isinstance(record, dict):
        return False
    return record.get("delivery_state") == "pending" or record.get("state") in {
        "running", "finalizing",
    }


def _delivery_surface_available(watch: dict) -> bool:
    """Preflight delivery before pulling, so a failed route keeps its row pending."""
    surface = _watch_surface(watch)
    if surface == "agent_bridge":
        return _agent_bridge_delivery_available()
    manager = getattr(_ctx, "_manager", None) if _ctx is not None else None
    if manager is None:
        # Test contexts provide inject_message directly.  Hermes PluginContext
        # always has a manager, so this does not weaken production fail-closed
        # behavior.
        return _ctx is not None
    if surface == "cli":
        cli = getattr(manager, "_cli_ref", None)
        # PluginContext.inject_message intentionally interrupts an active CLI
        # turn.  The supervisor uses the CLI's normal pending-input queue
        # instead, so lifecycle events are always handled as a later turn and
        # can never cancel the A2A call that registered their watch.
        pending = getattr(cli, "_pending_input", None)
        return cli is not None and callable(getattr(pending, "put", None))
    if surface == "gateway":
        return bool(getattr(manager, "has_gateway_message_injector", False))
    return False


def _delivery_label(watch: dict) -> str:
    surface = _watch_surface(watch)
    if surface == "agent_bridge" and _watch_is_durable(watch):
        return "agent-bridge-durable"
    if _watch_is_durable(watch):
        return "gateway-durable"
    if surface == "cli":
        return "cli-process"
    if surface == "gateway":
        return "gateway-process"
    return "unavailable"


def _poll_seconds() -> float:
    raw = os.getenv("AGENTHUB_SUPERVISOR_POLL_SECONDS", str(
        _DEFAULT_POLL_SECONDS))
    try:
        return min(max(float(raw), _MIN_POLL_SECONDS), _MAX_POLL_SECONDS)
    except (TypeError, ValueError):
        return _DEFAULT_POLL_SECONDS


def _retry_after_seconds(headers: Any) -> float | None:
    """Parse a bounded numeric Retry-After value from an HTTP response."""
    if headers is None:
        return None
    try:
        raw = headers.get("Retry-After")
        value = float(raw)
    except (AttributeError, TypeError, ValueError):
        return None
    return value if value >= 0 else None


def _poll_retry_delay(failure_count: int, error: Any = None) -> float:
    """Return bounded exponential backoff for a rate-limited poll request."""
    try:
        count = max(int(failure_count), 1)
    except (TypeError, ValueError):
        count = 1
    # Keep the exponent bounded even if an unhealthy endpoint remains rate
    # limited for hours.  The cap is one Gateway bucket window, and therefore
    # cannot turn a transient 429 into a request storm.
    multiplier = 2 ** min(count - 1, 6)
    delay = min(_MAX_POLL_BACKOFF_SECONDS,
                _poll_seconds() * multiplier)
    retry_after = getattr(error, "retry_after", None)
    if retry_after is not None:
        try:
            delay = max(delay, float(retry_after))
        except (TypeError, ValueError):
            pass
    return min(max(delay, _poll_seconds()), _MAX_POLL_BACKOFF_SECONDS)


def _max_session_messages() -> int:
    """Return the bounded physical-session rollover threshold."""
    raw = os.getenv("AGENTHUB_SUPERVISOR_MAX_SESSION_MESSAGES", "300")
    try:
        return min(max(int(raw), 50), 2000)
    except (TypeError, ValueError):
        return 300


def _endpoint() -> str:
    url = os.getenv("AGENTHUB_SUPERVISOR_URL", _DEFAULT_URL).strip()
    if url != _DEFAULT_URL:
        raise RuntimeError(
            "AGENTHUB_SUPERVISOR_URL must be the fixed qishuo loopback peer URL")
    return url


def _call_agenthub(action: str, *, context_id: str = _PULL_CONTEXT,
                   **fields) -> dict:
    token = os.getenv("AGENTHUB_A2A_TOKEN", "")
    if len(token) < 16:
        raise RuntimeError("AGENTHUB_A2A_TOKEN is missing or weak")
    control = {"agenthub": "v1", "action": action, **fields}
    body = {
        "jsonrpc": "2.0",
        "id": "agenthub-supervisor",
        "method": "SendMessage",
        "params": {"message": {
            "role": "user",
            "parts": [{
                "text": json.dumps(control, ensure_ascii=False,
                                   separators=(",", ":")),
                "mediaType": "application/json",
            }],
            "contextId": context_id,
        }},
    }
    request = urllib.request.Request(
        _endpoint(),
        data=json.dumps(body, ensure_ascii=False).encode("utf-8"),
        headers={
            "Authorization": f"Bearer {token}",
            "Content-Type": "application/json",
        },
        method="POST",
    )
    try:
        with urllib.request.urlopen(request, timeout=15) as response:
            result = json.loads(response.read().decode("utf-8"))
    except urllib.error.HTTPError as exc:
        raise _AgentHubHTTPError(
            exc.code, retry_after=_retry_after_seconds(exc.headers)) from exc
    except (OSError, ValueError) as exc:
        raise RuntimeError(
            f"agentHub supervisor unavailable: {type(exc).__name__}") from exc
    if result.get("error"):
        message = result["error"].get("message") or "agentHub rejected request"
        raise RuntimeError(str(message)[:240])
    rpc_result = result.get("result") or {}
    if not isinstance(rpc_result, dict):
        raise RuntimeError("agentHub returned invalid supervisor payload")
    if action == "tasks/get":
        task = rpc_result.get("task")
        if task is not None:
            if not isinstance(task, dict) or \
                    task.get("id") != fields.get("task_id"):
                raise RuntimeError("agentHub returned invalid supervisor payload")
            return task
    message = rpc_result.get("message") or {}
    parts = message.get("parts") or []
    text = next((part.get("text") for part in parts
                 if isinstance(part, dict) and isinstance(part.get("text"), str)),
                None)
    if not text:
        raise RuntimeError("agentHub returned no supervisor payload")
    payload = json.loads(text)
    if not isinstance(payload, dict):
        raise RuntimeError("agentHub returned invalid supervisor payload")
    return payload


