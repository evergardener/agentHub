def _session_surface(session_key: str = "") -> str:
    """Classify the current execution surface and its supported wake route."""
    key = session_key or _current_session_key()
    platform = _session_env("HERMES_SESSION_PLATFORM")
    source = _session_env("HERMES_SESSION_SOURCE")
    # hermes-web-ui runs a long-lived Python agent bridge.  It deliberately
    # reports source=tui for prompt compatibility, but its ``mt...`` session
    # is not an in-process CLI input queue.  The bridge owns a separate,
    # durable async-completion queue, so classify it before the TUI aliases.
    if platform == "agent_bridge":
        return "agent_bridge"
    if source in _CLI_SOURCES or platform in _CLI_SOURCES:
        return "cli"
    if source in _NON_DELIVERING_SURFACES or \
            platform in _NON_DELIVERING_SURFACES:
        return "unsupported"
    if _cli_ref_available() is True:
        return "cli"
    # Hermes Gateway routing keys are build_session_key() values with the
    # ``agent:`` namespace.  Bare CLI/worker keys (for example ``mt...``) are
    # process-local and must not be advertised as durable supervision.
    if key and key.startswith("agent:"):
        return "gateway"
    if key and not platform and not source:
        return "cli"
    if platform or source:
        return "gateway"
    return "unknown"


def _is_durable_route(surface: str, session_key: str) -> bool:
    """Return whether Hermes can recover this route after a process restart."""
    return (
        surface == "gateway" and session_key.startswith("agent:")
    ) or (
        surface == "agent_bridge" and bool(session_key)
    )


def _watch_record(*, task_id: str, context_id: str, session_key: str,
                  surface: str) -> dict:
    durable = _is_durable_route(surface, session_key)
    record = {
        "task_id": task_id,
        "context_id": context_id,
        "session_key": session_key,
        "owner_mode": surface,
        "owner_instance_id": "" if durable else _PROCESS_OWNER_ID,
        "durable": durable,
    }
    if surface == "agent_bridge":
        record["physical_session_id"] = session_key
    return record


def _watch_surface(watch: dict) -> str:
    value = str(watch.get("owner_mode") or "").strip().lower()
    if value in {"gateway", "cli", "agent_bridge"}:
        return value
    # Legacy state had no ownership metadata.  Only canonical Gateway keys can
    # be classified without the original session environment.  In particular,
    # never upgrade a bare ``mt...`` watch to agent_bridge merely because a new
    # bridge process is currently loading it: that would adopt and write into a
    # pre-upgrade user session.  Such watches remain unowned process-only state
    # and require an explicit fresh registration.
    session_key = str(watch.get("session_key") or "")
    return "gateway" if session_key.startswith("agent:") else "cli"


def _watch_is_durable(watch: dict) -> bool:
    value = watch.get("durable")
    if isinstance(value, bool):
        return value
    return _is_durable_route(
        _watch_surface(watch), str(watch.get("session_key") or ""))


def _process_owner_pid(owner_instance_id: Any) -> int | None:
    """Extract a PID only from the plugin's own process-owner token format."""
    if not isinstance(owner_instance_id, str):
        return None
    match = _PROCESS_OWNER_ID_RE.fullmatch(owner_instance_id.strip())
    if match is None:
        return None
    try:
        pid = int(match.group(1))
    except ValueError:  # pragma: no cover - guarded by the regular expression
        return None
    return pid if pid > 0 else None


def _process_is_alive(pid: int) -> bool:
    """Check liveness without turning permission or unknown errors into death."""
    try:
        os.kill(pid, 0)
    except ProcessLookupError:
        return False
    except PermissionError:
        # The process exists, but this Gateway does not have permission to
        # signal it.  Keep the watch rather than reclaiming a live owner.
        return True
    except OSError:
        # Any platform-specific/ambiguous error is fail-closed.
        return True
    return True


def _reap_dead_process_watches() -> None:
    """Stop and forget process-only watches whose owner PID has exited.

    CLI watches intentionally carry a random process token in addition to
    their PID.  The Gateway can use the PID to clean up abandoned watches,
    but it must never adopt or delete durable watches, the current process's
    own watches, or records with an unrecognised owner token.
    """
    if _ctx is None:
        return
    try:
        watches = _watches()
        candidates: dict[str, dict[str, str]] = {}
        for watch_id, watch in watches.items():
            if not isinstance(watch, dict) or _watch_is_durable(watch):
                continue
            if _watch_surface(watch) != "cli":
                continue
            owner_instance_id = watch.get("owner_instance_id")
            if owner_instance_id == _PROCESS_OWNER_ID:
                continue
            pid = _process_owner_pid(owner_instance_id)
            if pid is None or _process_is_alive(pid):
                continue
            task_id = str(watch.get("task_id") or "").strip()
            if task_id:
                candidates.setdefault(task_id, {})[str(watch_id)] = str(
                    owner_instance_id)

        if not candidates:
            return

        stopped_tasks: set[str] = set()
        for task_id in sorted(candidates):
            try:
                _call_agenthub("supervision/stop", task_id=task_id)
            except Exception as exc:
                logger.warning(
                    "agentHub supervision dead process-only watch stop "
                    "failed: task_id=%s reason=%s",
                    task_id, type(exc).__name__,
                )
            else:
                stopped_tasks.add(task_id)

        if not stopped_tasks:
            return
        stale_owners = {
            watch_id: owner_id
            for task_id in stopped_tasks
            for watch_id, owner_id in candidates[task_id].items()
        }
        # Re-read after the remote stop and remove only the exact stale owner.
        # A concurrent registration may reuse the server watch id with a new
        # process token; that fresh route must survive this cleanup.
        current = _watches()
        _save_watches({
            key: value for key, value in current.items()
            if stale_owners.get(key) != (
                value.get("owner_instance_id")
                if isinstance(value, dict) else None)
        })
        logger.info(
            "agentHub supervision reaped dead process-only watches: "
            "watch_ids=%s",
            sorted(stale_owners),
        )
    except Exception as exc:
        # A cleanup failure must not take down the Gateway relay.  The next
        # poll will retry and the watch remains in state for evidence.
        logger.warning(
            "agentHub supervision dead process-only watch cleanup failed: %s",
            type(exc).__name__,
        )


def _owned_watches(surface: str | None = None) -> dict[str, dict]:
    """Return only watches this process is allowed to pull."""
    selected_surface = surface or _poll_surface
    if selected_surface not in {"gateway", "cli", "agent_bridge"}:
        return {}
    result = {}
    for watch_id, watch in _watches().items():
        if not isinstance(watch, dict):
            continue
        watch_surface = _watch_surface(watch)
        # The long-lived Gateway is the restart-safe relay for Studio-owned
        # watches.  Agent-bridge workers are created lazily, so after a Studio
        # restart there may be no profile worker alive to poll agentHub.  The
        # Gateway can still publish the wake through Hermes' durable native
        # completion queue; the Studio bridge consumes that queue separately.
        gateway_bridge_relay = (
            selected_surface == "gateway"
            and watch_surface == "agent_bridge"
            and _watch_is_durable(watch)
            and _agent_bridge_delivery_available()
        )
        # A durable WebUI watch has exactly one poll owner: the long-lived
        # Gateway relay.  A lazily-created Agent Bridge worker must never pull
        # the same outbox, even when the native dispatcher is unavailable;
        # otherwise both processes spend the shared Gateway rate-limit bucket
        # and can race duplicate delivery.  If the relay is unavailable the
        # watch stays pending (fail-closed) until it can be recovered.
        if watch_surface == "agent_bridge":
            if not gateway_bridge_relay:
                continue
        elif watch_surface != selected_surface:
            continue
        if _watch_is_durable(watch):
            result[watch_id] = watch
            continue
        if watch.get("owner_instance_id") == _PROCESS_OWNER_ID:
            result[watch_id] = watch
    return result


