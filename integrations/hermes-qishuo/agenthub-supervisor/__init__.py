def _stream_key(session_id: Any, turn_id: Any) -> tuple[str, str]:
    return (str(session_id or ""), str(turn_id or ""))


def _stream_recovery_bindings(session_id: Any, turn_id: Any,
                              recovered: Any = None) -> list[dict]:
    """Return only durable WebUI bindings for one verified recovery turn."""
    key = _stream_key(session_id, turn_id)
    if not key[0] or not key[1]:
        return []
    if recovered is None:
        with _recovery_turn_lock:
            recovered = list(_recovery_turns.get(key, []))
    if not isinstance(recovered, list):
        return []
    # The recovery records are already authenticated by
    # _trusted_message_envelopes.  Re-check the live watch here so stream
    # observer hooks cannot turn an unrelated Hermes turn into a WebUI write.
    with _delivery_lock:
        watches = _watches()
    bindings = []
    seen = set()
    for item in recovered:
        if not isinstance(item, dict):
            continue
        notification_id = item.get("notification_id")
        watch_id = item.get("watch_id")
        message_id = item.get("message_id")
        context_id = item.get("context_id")
        if not isinstance(notification_id, str) or notification_id in seen:
            continue
        if not isinstance(watch_id, str) or not isinstance(message_id, str):
            continue
        if not isinstance(context_id, str) or not context_id:
            continue
        watch = watches.get(watch_id)
        if not isinstance(watch, dict) or \
                _watch_surface(watch) != "agent_bridge" or \
                not _watch_is_durable(watch):
            continue
        if watch.get("context_id") != context_id or \
                watch.get("task_id") != item.get("task_id"):
            continue
        seen.add(notification_id)
        bindings.append({
            "notification_id": notification_id,
            "watch_id": watch_id,
            "task_id": item.get("task_id"),
            "context_id": context_id,
            "message_id": message_id,
        })
    return bindings


def _stream_prepare_recovery(session_id: Any, turn_id: Any,
                             recovered: list[dict]) -> None:
    """Create a local stream ledger before the provider starts emitting."""
    bindings = _stream_recovery_bindings(session_id, turn_id, recovered)
    if not bindings:
        return
    key = _stream_key(session_id, turn_id)
    with _stream_state_lock:
        state = _stream_states.get(key)
        if not isinstance(state, dict):
            state = {
                "session_id": key[0],
                "turn_id": key[1],
                "post_started": False,
                "hook_seen": False,
                "streams": {},
            }
            _stream_states[key] = state
        streams = state.setdefault("streams", {})
        for binding in bindings:
            notification_id = binding["notification_id"]
            if notification_id in streams:
                continue
            streams[notification_id] = {
                **binding,
                "stream_id": f"st-{uuid4().hex}",
                "draft": "",
                "sent_text": "",
                "next_seq": 0,
                "start_seen": False,
                "start_sent": False,
                "observed": False,
                "terminal": False,
                "terminal_phase": None,
                "terminal_text": "",
                "finish_sent": False,
                "abort_sent": False,
                "abort_deadline": None,
                "last_error": None,
                "iterations": set(),
                "send_lock": threading.Lock(),
                "terminal_event": threading.Event(),
            }


def _stream_mark_hook_seen(event: dict) -> bool:
    """Record activity without doing network or provider work in a hook."""
    key = _stream_key(event.get("session_id"), event.get("turn_id"))
    with _stream_state_lock:
        state = _stream_states.get(key)
        if not isinstance(state, dict) or state.get("post_started"):
            return False
        # A single bit avoids walking every recovered message in the token
        # callback. The worker (or terminal path) fans this out to bindings.
        state["hook_seen"] = True
        return True


def _stream_event_from_payload(kind: str, payload: dict[str, Any]) -> dict | None:
    if not isinstance(payload, dict):
        return None
    session_id = str(payload.get("session_id") or "").strip()
    turn_id = str(payload.get("turn_id") or "").strip()
    if not session_id or not turn_id:
        return None
    event: dict[str, Any] = {
        "kind": kind,
        "session_id": session_id,
        "turn_id": turn_id,
    }
    try:
        event["iteration"] = int(payload.get("iteration") or 0)
    except (TypeError, ValueError):
        event["iteration"] = 0
    if kind == "delta":
        # Hermes exposes reasoning as the same hook with kind=reasoning.  Do
        # not put that content into the bounded queue at all.
        delta_kind = str(payload.get("kind") or "text").strip().lower()
        if delta_kind != "text":
            return None
        delta = payload.get("delta")
        if not isinstance(delta, str) or not delta:
            return None
        event["delta"] = delta[:_STREAM_MAX_DELTA_CHARS]
    elif kind == "end":
        event["finished"] = bool(payload.get("finished"))
        final_text = payload.get("final_text")
        if isinstance(final_text, str):
            event["final_text"] = final_text[:_STREAM_MAX_TEXT_CHARS]
        error = payload.get("error")
        if isinstance(error, str):
            event["error"] = error[:1000]
    return event


def _stream_start_worker() -> None:
    global _stream_thread
    with _stream_thread_lock:
        if _stream_stop.is_set():
            return
        if _stream_thread is not None and _stream_thread.is_alive():
            return
        events = _stream_queue
        stop = _stream_stop
        _stream_thread = threading.Thread(
            target=_stream_batch_loop,
            args=(events, stop),
            name="plugin:agenthub-supervisor:stream",
            daemon=True,
        )
        _stream_thread.start()


def _stream_queue_event(event: dict) -> bool:
    """Put one event without ever waiting for the worker."""
    global _stream_dropped_events
    with _stream_thread_lock:
        if _stream_stop.is_set():
            return False
        events = _stream_queue
        try:
            events.put_nowait(event)
            return True
        except queue.Full:
            # Preserve control events (start/end/wake) by discarding one
            # oldest item. Delta loss is explicitly tolerated: the authoritative
            # post_llm_call final is sent in the finish phase below.
            if event.get("kind") == "delta":
                with _stream_state_lock:
                    _stream_dropped_events += 1
                return False
            try:
                events.get_nowait()
                events.task_done()
            except queue.Empty:
                pass
            try:
                events.put_nowait(event)
                return True
            except queue.Full:
                with _stream_state_lock:
                    _stream_dropped_events += 1
                return False


def _stream_enqueue_hook(event_type: str, **payload: Any) -> bool:
    """Normalize and enqueue a stream observer event in O(1) hook work."""
    event = _stream_event_from_payload(event_type, payload)
    if event is None:
        return False
    # This is intentionally only a tiny local ledger bit. All text assembly
    # and all I/O remain in _stream_batch_loop.
    if not _stream_mark_hook_seen(event):
        return False
    _stream_start_worker()
    return _stream_queue_event(event)


def _on_stream_start(**payload: Any) -> None:
    _stream_enqueue_hook("start", **payload)


def _on_stream_delta(**payload: Any) -> None:
    _stream_enqueue_hook("delta", **payload)


def _on_stream_end(**payload: Any) -> None:
    _stream_enqueue_hook("end", **payload)


def _stream_process_event(event: dict) -> None:
    key = _stream_key(event.get("session_id"), event.get("turn_id"))
    with _stream_state_lock:
        state = _stream_states.get(key)
        if not isinstance(state, dict) or state.get("post_started"):
            return
        streams = state.get("streams", {})
        event_kind = event.get("kind")
        if event_kind == "start":
            iteration = event.get("iteration", 0)
            for stream in streams.values():
                if not isinstance(stream, dict) or stream.get("terminal"):
                    continue
                stream["observed"] = True
                stream["start_seen"] = True
                stream.setdefault("iterations", set()).add(iteration)
                # A failed provider attempt may be followed by a retry. A
                # fresh start within the grace window cancels the tentative
                # abort from the prior attempt.
                stream["abort_deadline"] = None
            return
        if event_kind == "delta":
            text = event.get("delta")
            if not isinstance(text, str) or not text:
                return
            for stream in streams.values():
                if not isinstance(stream, dict) or stream.get("terminal"):
                    continue
                stream["observed"] = True
                draft = str(stream.get("draft") or "")
                remaining = _STREAM_MAX_TEXT_CHARS - len(draft)
                if remaining > 0:
                    stream["draft"] = draft + text[:remaining]
            return
        if event_kind == "end":
            for stream in streams.values():
                if not isinstance(stream, dict) or stream.get("terminal"):
                    continue
                stream["observed"] = True
                if not event.get("finished"):
                    stream["last_error"] = event.get("error") or "stream ended"
                    stream["abort_deadline"] = (
                        time.monotonic() + _STREAM_ABORT_GRACE_SECONDS)


def _stream_raw_phase(key: tuple[str, str], notification_id: str,
                      phase: str, text: str) -> bool:
    """Send one phase while serializing it with post-turn finalization."""
    with _stream_state_lock:
        state = _stream_states.get(key)
        streams = state.get("streams", {}) if isinstance(state, dict) else {}
        stream = streams.get(notification_id)
        if not isinstance(stream, dict):
            return False
        send_lock = stream.get("send_lock")
    # ``threading.Lock`` is a factory on some supported Python versions; use
    # the context-manager protocol instead of an isinstance check.
    if not hasattr(send_lock, "__enter__"):
        return False
    with send_lock:
        with _stream_state_lock:
            state = _stream_states.get(key)
            streams = state.get("streams", {}) \
                if isinstance(state, dict) else {}
            stream = streams.get(notification_id)
            if not isinstance(stream, dict):
                return False
            if phase == "update" and (
                    (stream.get("terminal") and not (
                        stream.get("terminal_phase") == "finish"
                        and text == stream.get("terminal_text")))
                    or (isinstance(state, dict)
                        and state.get("post_started")
                        and not (stream.get("terminal_phase") == "finish"
                                 and text == stream.get("terminal_text")))):
                return False
            if phase == "finish" and stream.get("terminal_phase") != "finish":
                return False
            if phase == "abort" and stream.get("terminal_phase") != "abort":
                return False
            if phase == "start" and stream.get("start_sent"):
                return True
            if phase == "finish" and stream.get("finish_sent"):
                return True
            if phase == "abort" and stream.get("abort_sent"):
                return True
            seq = int(stream.get("next_seq") or 0)
            context_id = stream.get("context_id")
            message_id = stream.get("message_id")
            stream_id = stream.get("stream_id")
        try:
            _call_agenthub(
                "conversations/stream",
                context_id=context_id,
                message_id=message_id,
                phase=phase,
                stream_id=stream_id,
                seq=seq,
                text=text[:_STREAM_MAX_TEXT_CHARS],
            )
        except Exception as exc:
            logger.warning(
                "agentHub conversation stream phase failed: "
                "message_id=%s phase=%s seq=%s reason=%s",
                message_id, phase, seq, type(exc).__name__,
            )
            if phase in {"finish", "abort"}:
                event = stream.get("terminal_event")
                if isinstance(event, threading.Event):
                    event.set()
            return False
        with _stream_state_lock:
            state = _stream_states.get(key)
            stream = (state.get("streams", {}).get(notification_id)
                      if isinstance(state, dict) else None)
            if not isinstance(stream, dict):
                return True
            stream["next_seq"] = seq + 1
            if phase == "start":
                stream["start_sent"] = True
                stream["sent_text"] = ""
            elif phase == "update":
                stream["sent_text"] = text
            elif phase == "finish":
                stream["finish_sent"] = True
                stream["sent_text"] = text
                event = stream.get("terminal_event")
                if isinstance(event, threading.Event):
                    event.set()
            elif phase == "abort":
                stream["abort_sent"] = True
                event = stream.get("terminal_event")
                if isinstance(event, threading.Event):
                    event.set()
        return True


def _stream_flush_one(key: tuple[str, str], notification_id: str,
                      *, now: float) -> None:
    with _stream_state_lock:
        state = _stream_states.get(key)
        stream = (state.get("streams", {}).get(notification_id)
                  if isinstance(state, dict) else None)
        if not isinstance(stream, dict) or not stream.get("observed"):
            return
        terminal = bool(stream.get("terminal"))
        phase = stream.get("terminal_phase")
        terminal_text = str(stream.get("terminal_text") or "")
        draft = str(stream.get("draft") or "")
        sent_text = str(stream.get("sent_text") or "")
        start_sent = bool(stream.get("start_sent"))
        abort_deadline = stream.get("abort_deadline")
        post_started = bool(state.get("post_started")) if isinstance(state, dict) else False
    if terminal:
        if phase in {"finish", "abort"}:
            if phase == "finish" and stream.get("finish_sent"):
                return
            if phase == "abort" and stream.get("abort_sent"):
                return
            if not start_sent:
                if not _stream_raw_phase(key, notification_id, "start", ""):
                    return
            # The final model response can differ from the visible streamed
            # prefix (for example after a transform or provider retry). The
            # PostgreSQL protocol requires finish to retain the current
            # cumulative prefix, so publish the authoritative final as one
            # last update before finish when necessary.
            if phase == "finish" and not terminal_text.startswith(sent_text):
                if not _stream_raw_phase(
                        key, notification_id, "update", terminal_text):
                    return
            _stream_raw_phase(key, notification_id, phase, terminal_text)
        return
    if post_started:
        return
    if abort_deadline is not None and now >= float(abort_deadline):
        with _stream_state_lock:
            state = _stream_states.get(key)
            stream = (state.get("streams", {}).get(notification_id)
                      if isinstance(state, dict) else None)
            if not isinstance(stream, dict) or stream.get("terminal"):
                return
            stream["terminal"] = True
            stream["terminal_phase"] = "abort"
            stream["terminal_text"] = draft
        _stream_flush_one(key, notification_id, now=now)
        return
    if not start_sent:
        if not _stream_raw_phase(key, notification_id, "start", ""):
            return
        start_sent = True
    if draft != sent_text:
        _stream_raw_phase(key, notification_id, "update", draft)


def _stream_flush(*, now: float | None = None) -> None:
    current = time.monotonic() if now is None else now
    with _stream_state_lock:
        keys = [
            (key, notification_id)
            for key, state in _stream_states.items()
            if isinstance(state, dict)
            for notification_id, stream in state.get("streams", {}).items()
            if isinstance(stream, dict)
        ]
    for key, notification_id in keys:
        try:
            _stream_flush_one(key, notification_id, now=current)
        except Exception as exc:
            logger.warning(
                "agentHub conversation stream batch failed: "
                "session_id=%s turn_id=%s reason=%s",
                key[0], key[1], type(exc).__name__,
            )


def _stream_batch_loop(events: "queue.Queue[dict]",
                       stop: threading.Event) -> None:
    deadline = time.monotonic() + _STREAM_BATCH_INTERVAL_SECONDS
    while not stop.is_set():
        timeout = max(0.0, deadline - time.monotonic())
        try:
            event = events.get(timeout=timeout)
        except queue.Empty:
            _stream_flush()
            deadline = time.monotonic() + _STREAM_BATCH_INTERVAL_SECONDS
            continue
        try:
            if event.get("kind") == "stop":
                return
            if event.get("kind") in {"start", "delta", "end"}:
                _stream_process_event(event)
            # A wake is emitted by post_llm_call so the authoritative finish
            # does not wait for the next interval. Other events are batched.
            if event.get("kind") == "wake":
                _stream_flush()
                deadline = time.monotonic() + _STREAM_BATCH_INTERVAL_SECONDS
            elif time.monotonic() >= deadline:
                _stream_flush()
                deadline = time.monotonic() + _STREAM_BATCH_INTERVAL_SECONDS
        except Exception:
            logger.warning("agentHub conversation stream worker event failed",
                           exc_info=True)
        finally:
            events.task_done()


def _stream_mark_post_started(session_id: Any, turn_id: Any) -> None:
    key = _stream_key(session_id, turn_id)
    with _stream_state_lock:
        state = _stream_states.get(key)
        if isinstance(state, dict):
            state["post_started"] = True


def _stream_request_terminal(session_id: Any, turn_id: Any,
                             notification_id: str, *, phase: str,
                             text: str) -> None:
    if phase not in {"finish", "abort"}:
        return
    key = _stream_key(session_id, turn_id)
    with _stream_state_lock:
        state = _stream_states.get(key)
        stream = (state.get("streams", {}).get(notification_id)
                  if isinstance(state, dict) else None)
        if not isinstance(state, dict) or not state.get("hook_seen") or \
                not isinstance(stream, dict):
            return
        # The callback records only one turn-level bit to stay O(1); bind the
        # particular message lazily when its terminal phase is requested.
        stream["observed"] = True
        send_lock = stream.get("send_lock")
    if not hasattr(send_lock, "__enter__"):
        return
    # Wait for an already-running progress request, then install the terminal
    # fence. Any later delta/end is ignored even if it is still in Hermes'
    # cross-hook queue.
    with send_lock:
        with _stream_state_lock:
            state = _stream_states.get(key)
            stream = (state.get("streams", {}).get(notification_id)
                      if isinstance(state, dict) else None)
            if not isinstance(stream, dict):
                return
            if stream.get("terminal"):
                return
            stream["terminal"] = True
            stream["terminal_phase"] = phase
            stream["terminal_text"] = text[:_STREAM_MAX_TEXT_CHARS]
            terminal_event = stream.get("terminal_event")
    _stream_start_worker()
    _stream_queue_event({"kind": "wake", "session_id": key[0],
                         "turn_id": key[1]})
    if threading.current_thread() is not _stream_thread and \
            isinstance(terminal_event, threading.Event):
        terminal_event.wait(timeout=_STREAM_TERMINAL_WAIT_SECONDS)


def _stop_stream_relay() -> None:
    """Stop the batching worker and discard stream state on plugin unload."""
    global _stream_queue, _stream_stop, _stream_thread
    with _stream_thread_lock:
        stop = _stream_stop
        events = _stream_queue
        thread = _stream_thread
        stop.set()
        try:
            events.put_nowait({"kind": "stop"})
        except queue.Full:
            pass
    if thread is not None and thread is not threading.current_thread():
        thread.join(timeout=2.0)
    with _stream_thread_lock:
        if _stream_thread is thread:
            _stream_thread = None
        _stream_queue = queue.Queue(maxsize=_STREAM_QUEUE_SIZE)
        _stream_stop = threading.Event()
    with _stream_state_lock:
        _stream_states.clear()

