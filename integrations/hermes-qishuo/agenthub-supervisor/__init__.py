class _DeliveryLedgerLock:
    """Serialize delivery-ledger transactions across plugin processes.

    ``PluginState.set`` protects each individual JSON read/write, but a
    delivery reservation is a read-modify-write transaction.  The sidecar
    lock therefore has to be acquired before callers read the state and held
    until the final write.  It is deliberately a different sidecar from
    PluginState's ``.state.json.lock``; every delivery path takes this lock
    first and then lets PluginState take its own lock, so no path can acquire
    the two locks in the reverse order.

    Test contexts (and older Hermes hosts) may expose no ``state.path``.  In
    that case the process-local reentrant lock still preserves the historical
    behavior without pretending to provide cross-process protection.
    """

    def __init__(self) -> None:
        self._thread_lock = threading.RLock()
        self._local = threading.local()

    @staticmethod
    def _path() -> Path | None:
        state = getattr(_ctx, "state", None) if _ctx is not None else None
        state_path = getattr(state, "path", None)
        if state_path is None:
            return None
        try:
            path = Path(state_path)
        except TypeError as exc:
            raise RuntimeError(
                "PluginState.path must be a filesystem path for delivery locking"
            ) from exc
        if not path.name or path.name in {".", ".."}:
            raise RuntimeError(
                "PluginState.path must name a state file for delivery locking"
            )
        # Keep this separate from PluginState's own `.state.json.lock` so the
        # lock order remains one-way: delivery sidecar, then PluginState.
        return path.with_name(f".{path.name}.delivery.lock")

    @staticmethod
    def _acquire_file(handle) -> None:
        if os.name == "nt":  # pragma: no cover - exercised on Windows CI
            import msvcrt

            if handle.seek(0, os.SEEK_END) == 0:
                handle.write(b"\0")
                handle.flush()
            handle.seek(0)
            msvcrt.locking(handle.fileno(), msvcrt.LK_LOCK, 1)
        else:
            import fcntl

            fcntl.flock(handle.fileno(), fcntl.LOCK_EX)

    @staticmethod
    def _release_file(handle) -> None:
        if os.name == "nt":  # pragma: no cover - exercised on Windows CI
            import msvcrt

            handle.seek(0)
            msvcrt.locking(handle.fileno(), msvcrt.LK_UNLCK, 1)
        else:
            import fcntl

            fcntl.flock(handle.fileno(), fcntl.LOCK_UN)

    def __enter__(self):
        self._thread_lock.acquire()
        depth = int(getattr(self._local, "depth", 0) or 0)
        if depth:
            self._local.depth = depth + 1
            return self

        handle = None
        try:
            lock_path = self._path()
            if lock_path is not None:
                lock_path.parent.mkdir(parents=True, exist_ok=True)
                handle = open(lock_path, "a+b")
                self._acquire_file(handle)
            self._local.depth = 1
            self._local.handle = handle
            return self
        except Exception:
            if handle is not None:
                handle.close()
            self._thread_lock.release()
            raise

    def __exit__(self, exc_type, exc_value, traceback):
        depth = int(getattr(self._local, "depth", 0) or 0)
        if depth <= 0:  # pragma: no cover - defensive misuse guard
            self._thread_lock.release()
            return False
        if depth > 1:
            self._local.depth = depth - 1
            self._thread_lock.release()
            return False

        handle = getattr(self._local, "handle", None)
        try:
            if handle is not None:
                self._release_file(handle)
        finally:
            if handle is not None:
                handle.close()
            self._local.depth = 0
            self._local.handle = None
            self._thread_lock.release()
        return False


