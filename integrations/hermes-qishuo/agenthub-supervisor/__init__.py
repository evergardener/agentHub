def register(ctx) -> None:
    global _ctx
    _ctx = ctx
    ctx.register_hook("transform_tool_result", _transform_tool_result)
    ctx.register_hook("on_session_start", _ensure_polling)
    ctx.register_hook("pre_llm_call", _pre_llm_recovery_context)
    ctx.register_hook("post_llm_call", _post_llm_recovery_response)
    ctx.register_hook("on_stream_start", _on_stream_start)
    ctx.register_hook("on_stream_delta", _on_stream_delta)
    ctx.register_hook("on_stream_end", _on_stream_end)
    ctx.on_unload(_stop_polling)
    for name, (handler, description, parameters) in _TOOLS.items():
        ctx.register_tool(
            name=name,
            # Do not register into Hermes' built-in ``a2a`` toolset.  That is
            # an override requiring a capability this plugin deliberately
            # does not hold, and API-server recovery turns would silently omit
            # every supervisor tool.  A dedicated plugin toolset is
            # auto-discovered on those turns without broadening a2a_call.
            toolset="agenthub_supervisor",
            schema={"name": name, "description": description,
                    "parameters": parameters},
            handler=handler,
            description=description,
            emoji="⏱️",
        )
    _ensure_polling()
