    """Read one exact native interaction through the authenticated context."""
    task_id = str(args.get("task_id") or "").strip()
    interaction_id = str(args.get("interaction_id") or "").strip()
    context_id = str(args.get("context_id") or "").strip()
    if not task_id or len(task_id) > 128 or not interaction_id or \
            len(interaction_id) > 128 or not context_id:
        return (
            "Error: valid task_id, interaction_id, and context_id are required.")
